/**
 * Genuine GCC GIMPLE Intermediate Representation (IR) Analyzer
 * Formats and analyzes GCC GIMPLE 3-address code representations.
 */

class IrExtractor {
  extract(rawGimple, compilerVersion = '16.2.0') {
    if (!rawGimple || rawGimple.trim().length === 0) {
      return {
        status: 'unavailable',
        reason: 'GIMPLE intermediate representation was not generated by GCC (likely due to syntax or semantic errors in previous phases).',
        producingTool: 'GCC GIMPLE Dump Facility (-fdump-tree-gimple)',
        code: '',
        functions: [],
        instructionCount: 0,
        temporaryVariables: [],
      };
    }

    const lines = rawGimple.split(/\r?\n/);
    const functions = [];
    let currentFunc = null;
    let totalInstructions = 0;
    const tempVars = new Set();

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const trimmed = line.trim();

      // Detect function boundary in GIMPLE (unindented, non-statement function definition)
      // Example: int main () or void calculate (int a, int b)
      const isUnindented = !line.startsWith(' ') && !line.startsWith('\t');
      const funcMatch = isUnindented && !trimmed.endsWith(';') && line.match(/^([a-zA-Z0-9_* ]+)\s+([a-zA-Z0-9_]+)\s*\(([^)]*)\)/);
      if (funcMatch && !trimmed.startsWith('//') && !trimmed.startsWith('/*')) {
        if (currentFunc) {
          functions.push(currentFunc);
        }
        currentFunc = {
          signature: trimmed,
          name: funcMatch[2],
          returnType: funcMatch[1].trim(),
          parameters: funcMatch[3].trim(),
          lines: [line],
          temporaries: [],
          instructions: [],
        };
        continue;
      }

      if (currentFunc) {
        currentFunc.lines.push(line);

        // Detect temporary variables (D.1234 or _1 or similar GCC internal temporaries)
        const dMatches = line.match(/\b(D\.[0-9]+)\b/g);
        if (dMatches) {
          for (const d of dMatches) {
            tempVars.add(d);
            if (!currentFunc.temporaries.includes(d)) {
              currentFunc.temporaries.push(d);
            }
          }
        }
        const ssaMatches = line.match(/\b([a-zA-Z0-9_]+_[0-9]+)\b/g);
        if (ssaMatches) {
          for (const s of ssaMatches) {
            tempVars.add(s);
            if (!currentFunc.temporaries.includes(s)) {
              currentFunc.temporaries.push(s);
            }
          }
        }

        // Detect 3-address instruction lines (assignments, calls, returns, gotos)
        if (
          trimmed.includes('=') ||
          trimmed.startsWith('return') ||
          trimmed.startsWith('goto') ||
          trimmed.startsWith('if') ||
          trimmed.includes('(')
        ) {
          if (!trimmed.startsWith('{') && !trimmed.startsWith('}') && !trimmed.endsWith(';')) {
            // normal
          }
          currentFunc.instructions.push(trimmed);
          totalInstructions++;
        }
      }
    }

    if (currentFunc) {
      functions.push(currentFunc);
    }

    return {
      status: 'success',
      code: rawGimple,
      functions,
      totalInstructions,
      temporaryVariables: Array.from(tempVars),
      compiler: `GCC ${compilerVersion}`,
      producingTool: 'GCC -fdump-tree-gimple (GENERIC to GIMPLE Lowering)',
      explanation:
        'GIMPLE is the target-independent tree-based intermediate representation used by GCC. ' +
        'It decomposes complex nested C expressions into 3-address code statements with explicit temporary variables ' +
        '(e.g., D.xxxx) and simplified control flow, preparing the code for optimization passes.',
    };
  }
}

module.exports = new IrExtractor();
