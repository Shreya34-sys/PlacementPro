class AssemblyAnalyzer {
  analyze(rawAssembly, meta = {}) {
    if (!rawAssembly || rawAssembly.trim().length === 0) {
      return {
        status: 'unavailable',
        reason: 'Assembly code could not be generated due to compilation errors.',
        rawAssembly: '',
        instructions: [],
        sections: [],
        functions: [],
        metadata: meta,
        producingTool: 'GCC -S -fverbose-asm (Target Code Generator)',
      };
    }

    const lines = rawAssembly.split(/\r?\n/);
    const parsedLines = [];
    const functions = [];
    const sections = new Set();
    let currentFunction = null;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const trimmed = line.trim();

      // Check section directive (.text, .data, .rdata, .bss)
      const secMatch = trimmed.match(/^\.(text|data|rdata|bss|section\s+[^\s]+)/);
      if (secMatch) {
        sections.add(secMatch[1]);
      }

      // Check function label (e.g. main:)
      const labelMatch = line.match(/^([a-zA-Z0-9_]+):/);
      if (labelMatch && !trimmed.startsWith('.')) {
        currentFunction = {
          name: labelMatch[1],
          startLine: i + 1,
          instructionCount: 0,
        };
        functions.push(currentFunction);
      }

      // Check source comment generated by -fverbose-asm
      let sourceComment = null;
      const commentMatch = line.match(/#\s*(program\.c:\d+:.*)$/);
      if (commentMatch) {
        sourceComment = commentMatch[1];
      }

      // Extract instruction mnemonic
      let instructionMnemonic = null;
      let instructionExplanation = null;
      const instrMatch = trimmed.match(/^([a-z]+[0-9]*)\s*([^#;]*)/);
      if (instrMatch && !trimmed.startsWith('.') && !trimmed.endsWith(':')) {
        const mnemonic = instrMatch[1];
        if (INSTRUCTION_EXPLANATIONS[mnemonic]) {
          instructionMnemonic = mnemonic;
          instructionExplanation = INSTRUCTION_EXPLANATIONS[mnemonic];
        }
        if (currentFunction) {
          currentFunction.instructionCount++;
        }
      }

      parsedLines.push({
        lineNumber: i + 1,
        rawText: line,
        isLabel: trimmed.endsWith(':'),
        isDirective: trimmed.startsWith('.'),
        isComment: trimmed.startsWith('#'),
        mnemonic: instructionMnemonic,
        explanation: instructionExplanation,
        sourceComment,
      });
    }

    return {
      status: 'success',
      rawAssembly,
      parsedLines,
      sections: Array.from(sections),
      functions,
      totalLines: lines.length,
      targetArchitecture: meta.targetArchitecture || 'Unavailable',
      compilerVersion: meta.compilerVersion || 'Unavailable',
      flags: meta.flags || ['-S', '-fverbose-asm'],
      instructionDictionary: INSTRUCTION_EXPLANATIONS,
      registerDictionary: REGISTER_EXPLANATIONS,
      producingTool: 'GCC -S -fverbose-asm (GNU Assembler Output)',
      explanation:
        'Target Code Generation translates optimized intermediate code into target-specific machine assembly instructions, ' +
        'assigning registers, computing memory stack offsets, and adhering to the calling convention for the selected target.',
    };
  }
}

module.exports = new AssemblyAnalyzer();
